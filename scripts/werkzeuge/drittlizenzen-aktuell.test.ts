// drittlizenzen-aktuell.test.ts
// Prüft an einem Wegwerf-Aufbau, ob die Aktualitätsprüfung von THIRD-PARTY-LICENSES
// geänderte npm-Laufzeitpakete und Rust-Abhängigkeiten erkennt, Versionssprünge des
// eigenen Crates aber hinnimmt; außerdem die Ermittlung der Lucide-Version.
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  cargoLockFingerabdruck,
  drittlizenzenAbweichungen,
  drittlizenzenText,
  lucideVersion,
  npmKomponenten,
} from './drittlizenzenAblauf';

let ordner: string;
beforeEach(() => {
  ordner = mkdtempSync(join(tmpdir(), 'lexlata-drittlizenzen-aktuell-'));
});
afterEach(() => rmSync(ordner, { recursive: true, force: true }));

const schreiben = (pfad: string, inhalt: string) => {
  mkdirSync(join(ordner, pfad, '..'), { recursive: true });
  writeFileSync(join(ordner, pfad), inhalt);
};

function cargoLock(appVersion: string, serdeVersion: string, zeilenende = '\n'): string {
  return [
    '# This file is automatically @generated by Cargo.',
    'version = 4',
    '',
    '[[package]]',
    'name = "app"',
    `version = "${appVersion}"`,
    'dependencies = [',
    ' "serde",',
    ']',
    '',
    '[[package]]',
    'name = "serde"',
    `version = "${serdeVersion}"`,
    '',
  ].join(zeilenende);
}

function npmInstallieren(pakete: { name: string; version: string; lizenz: string }[]) {
  const packages: Record<string, object> = { '': { name: 'app' } };
  for (const { name, version, lizenz } of pakete) {
    packages[`node_modules/${name}`] = { version };
    schreiben(
      `node_modules/${name}/package.json`,
      JSON.stringify({ name, version, license: lizenz, author: 'Urheberin' }),
    );
  }
  schreiben('package-lock.json', JSON.stringify({ packages }));
}

/** Erzeugt THIRD-PARTY-LICENSES wie npm run drittlizenzen aus dem aktuellen Aufbau. */
function erzeugen() {
  const rust = {
    herkunft: 'Rust' as const,
    name: 'serde',
    version: '1.0.0',
    lizenz: 'MIT',
    lizenztexte: ['MIT-Text'],
  };
  const sonstige = {
    herkunft: 'Sonstige' as const,
    name: 'Schrift',
    version: '4',
    lizenz: 'OFL-1.1',
    lizenztexte: ['OFL-Text'],
  };
  const fingerabdruck = cargoLockFingerabdruck(
    readFileSync(join(ordner, 'src-tauri/Cargo.lock'), 'utf8'),
    'app',
  );
  schreiben(
    'THIRD-PARTY-LICENSES',
    drittlizenzenText([rust, ...npmKomponenten(ordner), sonstige], fingerabdruck),
  );
}

describe('Aktualität von THIRD-PARTY-LICENSES', () => {
  beforeEach(() => {
    schreiben('src-tauri/Cargo.lock', cargoLock('0.1.0', '1.0.0'));
    npmInstallieren([
      { name: 'react', version: '19.0.0', lizenz: 'MIT' },
      { name: 'saxes', version: '6.0.0', lizenz: 'ISC' },
    ]);
    erzeugen();
  });

  it('meldet nichts, solange der installierte Stand unverändert ist', () => {
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual([]);
  });

  it('nimmt Versionssprünge des eigenen Crates und andere Zeilenenden hin', () => {
    schreiben('src-tauri/Cargo.lock', cargoLock('0.2.0', '1.0.0', '\r\n'));
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual([]);
  });

  it('meldet geänderte Rust-Abhängigkeiten', () => {
    schreiben('src-tauri/Cargo.lock', cargoLock('0.1.0', '1.0.1'));
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual([
      'Rust: src-tauri/Cargo.lock hat sich seit der Erzeugung geändert.',
    ]);
  });

  it('meldet neue, entfernte und in Version oder Lizenz geänderte npm-Pakete', () => {
    rmSync(join(ordner, 'node_modules'), { recursive: true });
    npmInstallieren([
      { name: 'react', version: '19.1.0', lizenz: 'MIT' },
      { name: 'saxes', version: '6.0.0', lizenz: 'MIT' },
      { name: 'fflate', version: '0.8.3', lizenz: 'MIT' },
    ]);
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual([
      'npm: react 19.1.0 | MIT ist installiert, fehlt aber in der Datei.',
      'npm: saxes 6.0.0 | MIT ist installiert, fehlt aber in der Datei.',
      'npm: fflate 0.8.3 | MIT ist installiert, fehlt aber in der Datei.',
      'npm: react 19.0.0 | MIT steht in der Datei, ist aber nicht installiert.',
      'npm: saxes 6.0.0 | ISC steht in der Datei, ist aber nicht installiert.',
    ]);
  });

  it('meldet eine fehlende Datei und einen fehlenden Fingerabdruck', () => {
    const text = readFileSync(join(ordner, 'THIRD-PARTY-LICENSES'), 'utf8');
    schreiben('THIRD-PARTY-LICENSES', text.replace(/^Fingerabdruck .*\n/m, ''));
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual([
      'Rust: Fingerabdruck von Cargo.lock fehlt.',
    ]);
    rmSync(join(ordner, 'THIRD-PARTY-LICENSES'));
    expect(drittlizenzenAbweichungen(ordner, 'app')).toEqual(['THIRD-PARTY-LICENSES fehlt.']);
  });

  it('bricht ab, wenn das eigene Crate in Cargo.lock fehlt', () => {
    expect(() => cargoLockFingerabdruck(cargoLock('0.1.0', '1.0.0'), 'anderes')).toThrow(
      'Cargo.lock: Eintrag des eigenen Crates "anderes" fehlt.',
    );
  });
});

describe('Lucide-Version', () => {
  const svg = (version?: string) =>
    `${version ? `<!-- @license lucide-static v${version} - ISC -->\n` : ''}<svg></svg>\n`;

  it('liest die gemeinsame Version aus den Lizenzköpfen; Dateien ohne Kopf zählen nicht', () => {
    schreiben('quellen/a.svg', svg('1.28.0'));
    schreiben('quellen/b.svg', svg('1.28.0'));
    schreiben('quellen/eigen.svg', svg());
    schreiben('quellen/LIZENZ.txt', '@license lucide-static v9.9.9');
    expect(lucideVersion(join(ordner, 'quellen'))).toBe('1.28.0');
  });

  it('bricht bei uneinheitlichen oder fehlenden Versionen ab', () => {
    schreiben('quellen/a.svg', svg('1.28.0'));
    schreiben('quellen/b.svg', svg('1.29.0'));
    expect(() => lucideVersion(join(ordner, 'quellen'))).toThrow('gefunden: 1.28.0, 1.29.0');
    schreiben('leer/a.svg', svg());
    expect(() => lucideVersion(join(ordner, 'leer'))).toThrow('gefunden: keine');
  });
});
